#!/usr/bin/env bun
/**
 * Measures what the website and other documents state about this repository and writes docs/facts.lima, which
 * markanto.org reads at a commit, so that it states no number by hand.
 *
 *   bun scripts/facts.ts           write docs/facts.lima
 *   bun scripts/facts.ts --check   exit 1 if it differs from what is measured
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_MAX_MATRIX_SLOTS, HARD_MAX_MATRIX_SLOTS } from '../src/ast.js';

const repo = join(import.meta.dirname, '..');
const factsFile = join(repo, 'docs', 'facts.lima');

/** The output of a command, which must succeed: bun prints a test run's summary on stderr. */
function run(args: string[]): string {
  const result = spawnSync('bun', args, { cwd: repo, encoding: 'utf8', timeout: 5 * 60 * 1000 });
  if (result.status !== 0) throw new Error(`bun ${args.join(' ')}: ${result.error?.message ?? result.stderr}`);
  return `${result.stdout}${result.stderr}`;
}

/** The number the pattern captures in `text`, which must hold it. */
function measured(text: string, pattern: RegExp, what: string): number {
  const match = pattern.exec(text);
  if (!match) throw new Error(`no ${what} in the output`);
  return Number(match[1]!.replace(/[,_]/g, ''));
}

const manifest = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8'));
const language = readdirSync(join(repo, 'vendor', 'spec'))
  .filter((name) => /^\d+\.\d+\.\d+$/.test(name))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
  .at(-1);

run(['scripts/compat-report.mjs']);
const report = readFileSync(join(repo, 'test', 'compat', 'reports', 'latest.md'), 'utf8');
const tests = run(['test']);

const facts = `# Generated by scripts/facts.ts. Do not edit.
# Regenerate with: bun scripts/facts.ts

package:
  version: "${manifest.version}"
  runtime_dependencies: ${Object.keys(manifest.dependencies ?? {}).length}
language:
  version: "${language}"
corpus:
  cases: ${measured(run(['scripts/validate-corpus.mjs']), /OK: ([\d,]+) cases/, 'corpus size')}
tests:
  count: ${measured(tests, /^\s*(\d+) pass$/m, 'count of tests')}
commonmark:
  cases: ${measured(report, /\*\*total\*\* \| \*\*(\d+)\*\*/, 'count of CommonMark cases')}
  failed: ${measured(report, /`fail` \| (\d+)/, 'count of failed CommonMark cases')}
soak:
  documents_per_stream: ${measured(readFileSync(join(repo, 'scripts', 'soak.ts'), 'utf8'), /count: ([\d_]+)/, 'soak size')}
limits:
  default_max_matrix_slots: ${DEFAULT_MAX_MATRIX_SLOTS}
  hard_max_matrix_slots: ${HARD_MAX_MATRIX_SLOTS}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(factsFile, 'utf8') !== facts) {
    console.error('docs/facts.lima differs from what is measured: run bun scripts/facts.ts');
    process.exit(1);
  }
} else writeFileSync(factsFile, facts);
